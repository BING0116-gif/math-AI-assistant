LECTURES["closed-interval-properties"] = r"""## 这个知识点解决什么问题

闭区间上的连续函数有三条"豪华待遇"：**有界、取到最值、取遍中间值**。它们是介值定理的母定理，也是"证明某点取到某值"类题目的终极工具。

## 两条定理

**有界性定理**：$f$ 在 $[a,b]$ 上连续，则 $f$ 在 $[a,b]$ 上有界。

**最值定理**：$f$ 在 $[a,b]$ 上连续，则 $f$ 必在 $[a,b]$ 上取得最大值 $M$ 与最小值 $m$（即存在 $x_1, x_2 \in [a,b]$ 使 $f(x_1)=m$、$f(x_2)=M$）。

**两个前提缺一不可**，反例都在开区间或间断处：

- $f(x) = \tfrac1x$ 在 $(0, 1)$ 连续但无界（开区间丢待遇）；
- $f(x) = \begin{cases} \tfrac1x, & 0 < x \leq 1 \ 0, & x=0 \end{cases}$ 在 $[0,1]$ 上有间断点且无界（间断丢待遇）；
- $f(x) = x$ 在 $[0,1)$ 上有上确界 1 却取不到（开区间连最值都拿不到）。

## 与介值定理的联动（证明题工作流）

**加权平均题的完整逻辑链**：$f$ 在 $[a,b]$ 连续 $\Rightarrow$ 由最值定理存在最小值 $m$、最大值 $M$ $\Rightarrow$ $m \le \sum c_i f(x_i)/\sum c_i \le M$ $\Rightarrow$ 由介值定理存在 $\xi$ 使 $f(\xi) = W$。三步里"最值定理负责造出 $m, M$"，"介值定理负责取到"——两条定理是接力关系。

**常用推论**：若 $f(x_i) > 0$ 恒成立对有限个点，……（判断符号、找零点时先由最值锁定范围）。

## 实用估算

题目问"$f$ 在 $[a,b]$ 上最大值至少是多少"或"估计 $|\int f|$"时，最值定理保证最值存在，具体数值再由单调性或代值确定——先引用定理"存在"，再计算"是多少"。

## 学完之后

把三个反例各写一遍（开区间、有间断、取不到确界），体会"闭区间 + 连续"每个字都是待遇的一部分。"""

