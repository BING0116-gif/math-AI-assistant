LECTURES["squeeze-theorem"] = r"""## 这个知识点解决什么问题

夹逼定理处理"**算不出来但能两边卡住**"的极限：$n$ 项和式（每项都算不出但和有规律）、振荡函数（$\sin$ 套着无法化简）、取整函数。它把"精确计算"换成"精确放缩"。

## 定理内容与前提

若 $\varphi(x) \leq f(x) \leq g(x)$ 且 $\lim \varphi = \lim g = A$（**同一过程、两界极限相等**），则 $\lim f = A$。两个前提缺一不可：界要两侧都夹、极限要相等。

## 应用一：$n$ 项和式

$\lim_{n\to\infty}\left(\dfrac{1}{n^2+n+1} + \dfrac{2}{n^2+n+2} + \cdots + \dfrac{n}{n^2+n+n}\right)$。

第 $k$ 项分母在 $n^2+n+1$ 与 $n^2+2n$ 之间，于是

$$\frac{k}{n^2+2n} \leq \frac{k}{n^2+n+k} \leq \frac{k}{n^2+n+1}.$$

对 $k = 1, \dots, n$ 求和，两侧分别变成 $\dfrac{n(n+1)/2}{n^2+2n}$ 与 $\dfrac{n(n+1)/2}{n^2+n+1}$，都趋于 $\tfrac12$——极限 $\tfrac12$。**放缩模板**：分母不好统一时，全体换成"最大的分母"与"最小的分母"。

## 应用二：振荡型

$\lim_{x\to+\infty}\sin\left(\pi[x] + \tfrac{\pi^2}{x}\right)$：用 $\sin(\pi[x]+\theta) = (-1)^{[x]}\sin\theta$，虽然 $(-1)^{[x]}$ 振荡，但 $|\sin(\pi^2/x)| \leq \tfrac{\pi^2}{x} \to 0$，两侧 $\pm\tfrac{\pi^2}{x}$ 都趋于 0，夹逼得极限为 $0$。**"振幅趋于零的振荡"必归零**。

## 应用三：验证无穷小阶

$1-\cos x$：$\cos x \le 1$ 且 $1-\cos x = 2\sin^2\tfrac x2 \le 2 \cdot (\tfrac x2)^2 = \tfrac{x^2}{2}$，配合 $1-\cos x \geq 0$，得 $0 \leq 1-\cos x \leq \tfrac{x^2}{2}$——它因此是二阶无穷小。替换表里的系数就是这么夹出来的。

## 失效的情形

$\lim[g - \varphi] = 0$ **不能**代替"两界极限相等"：$\varphi = \sin^2 x$，$g = \sin^2 x + \tfrac1{x^2}$，$g - \varphi \to 0$，取 $f = \sin^2 x$ 夹在中间——极限不存在。夹逼要的是两界"到同一个地方去"。

## 学完之后

$n$ 项和式与振荡型各做一题，检查放缩方向是否写明。"""


