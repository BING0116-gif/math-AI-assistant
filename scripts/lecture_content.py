LECTURES["intermediate-value-theorem"] = r"""## 这个知识点解决什么问题

介值定理（含零点定理）是"证明方程有根"的标准武器：不要求解出根，只要求**论证根存在**。它是第一章证明题的主角，也是后续（罗尔定理等）微分中值定理的对照组。

## 定理内容

**零点定理**：$f$ 在 $[a,b]$ 上连续，$f(a) \cdot f(b) < 0$，则存在 $\xi \in (a,b)$ 使 $f(\xi) = 0$。

**介值定理**：$f$ 在 $[a,b]$ 上连续，$C$ 介于 $f(a)$ 与 $f(b)$（或最小值 $m$ 与最大值 $M$）之间，则存在 $\xi \in [a,b]$ 使 $f(\xi) = C$。

两条的关系：零点定理是介值定理取 $C = 0$ 的特例；一般介值可由"对 $f - C$ 用零点定理"得到。

## 证明题规范四步（以"方程 $xe^x = x + \cos\frac{\pi x}{2}$ 至少有一正根"为例）

1. **构造辅助函数**：把方程移项，令 $F(x) = xe^x - x - \cos\tfrac{\pi x}{2}$；
2. **选定区间、验证连续**：$F$ 是初等函数，在 $[0, 2]$ 上连续；
3. **端点异号**：$F(0) = -1 < 0$，$F(2) = 2e^2 - 1 > 0$；
4. **引用定理下结论**：由零点定理存在 $\xi \in (0, 2)$ 使 $F(\xi) = 0$，即原方程至少有一正根。

## 加权平均型（进阶变体）

$f$ 在 $[a,b]$ 连续，$a < x_1 < \cdots < x_n < b$，$c_i > 0$：存在 $\xi \in (a,b)$ 使 $f(\xi) = \dfrac{\sum c_i f(x_i)}{\sum c_i}$。思路：加权平均落在最小值 $m$ 与最大值 $M$ 之间（$m \le W \le M$），再由介值定理（在最值点之间）取到。**这一步"由最值 + 介值"的组合**是介值定理的标准进阶用法。

## 两条边界要心里有数

- 定理只给**存在性**，不给唯一性；要唯一性需另证单调（或其他手段）；
- "$f(a)f(b) > 0$"**推不出无根**——区间内可能有偶数个根；零点定理不可逆用。

## 学完之后

把"证明 $\sin x + x + 1 = 0$ 在 $(-\tfrac{\pi}{2}, \tfrac{\pi}{2})$ 有根"完整写一遍四步。"""

